/**
 * "이 리뷰에 이미 답글이 달렸는가" 판정.
 *
 * ★ 실측 2026-09-20 — 답글이 달린 리뷰에는 "답글 쓰기" 버튼이 **사라진다.**
 *   10건 중 1건만 버튼이 없었고 나머지 9건에는 있었다. 즉 답글 완료를 가리키는
 *   양(陽)의 표식이 아니라 **버튼의 부재**로 판정한다.
 *
 * ★ 왜 부재로 판정하는가 — 실패 방향이 안전한 쪽이기 때문이다.
 *   셀렉터가 깨졌을 때 두 방식의 결과가 정반대다.
 *
 *     부재로 판정(현행)  : 버튼을 못 찾음 → 전건 hasReply=true → 초안이 0건.
 *                          쓸모는 없지만 **사고는 없다.** 화면에 0건으로 바로 드러난다.
 *     양의 표식으로 판정 : 표식을 못 찾음 → 전건 hasReply=false → 이미 답글 단
 *                          리뷰에 또 초안을 만든다. 사장님이 두 번째 답글을 올리려다
 *                          실패하거나, 같은 리뷰가 큐에 계속 남는다.
 *
 *   조용히 틀리는 쪽보다 눈에 띄게 멈추는 쪽을 고른다. 이 방향을 뒤집지 말 것.
 *
 * ★ 데이터처리 9번(CLAUDE.md)과 같은 취지다 — 사장님이 앱에서 직접 답글을 달았을 수
 *   있으므로 DB 의 has_owner_reply 를 신뢰하지 않는다. 네이버도 마찬가지라 매번
 *   화면에서 다시 본다.
 */

/**
 * @param replyWriteButtonExists 리뷰 항목에 "답글 쓰기" 버튼이 있는가.
 *        스펙의 replyWriteButton 필드(parse: "exists") 결과를 그대로 넘긴다.
 */
export function deriveHasReply(replyWriteButtonExists: unknown): boolean {
  // exists 파싱은 boolean 을 내지만, 스펙에서 필드가 빠졌거나 파싱이 실패하면
  // undefined/null 이 온다. 그때도 "답글이 있다"(=처리하지 않는다) 쪽으로 붙인다.
  return replyWriteButtonExists !== true;
}
