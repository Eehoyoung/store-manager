-- 자동 게시 중지 스위치.
--
-- ★ V14 에서 auto_publish 를 지웠던 것과 방향이 반대로 보이지만 목적이 다르다.
--   V14 가 지운 것은 "가맹점주 승인 대기" 라는 **레거시 상태 머신**이었다. 이것은
--   개인정보 보호법 제37조의2 가 정한 **자동화된 결정에 대한 거부권**의 이행 수단이다.
--   처리방침 §9.4 가 "요청하면 자동 게시를 중지한다" 고 약속하는데, 그 약속을 지킬
--   수단이 코드에 없으면 지키지 못할 약속을 적어 둔 것이 된다.
--
-- ★ 기본값 TRUE — 지금까지의 동작과 같다. 끄는 것은 사장님의 선택이다.
--   끄면 초안은 계속 만들어지고 게시만 사람이 한다(초안 생성을 멈추지 않는다).
ALTER TABLE store_persona
    ADD COLUMN auto_publish BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN store_persona.auto_publish IS
    '자동 게시 여부. false 면 안전검사를 통과해도 예약하지 않고 사장님 확인 대기로 남긴다(제37조의2 거부권).';
