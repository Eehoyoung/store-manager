# ── tone 결정론 룰 (2026-09-17) ────────────────────────────────────────────
# ★ 실측 54건에서 모델이 낸 tone 이 50건 CALM 이었다. 신규 축이 사실상 상수였다.
# ★ 이 룰은 두 구멍을 한 번에 막는다 — tone 뿐 아니라 **risk 2 의 (가) 조건**이다.
#   CLAUDE.md 의 risk 2 는 (가)화·분노 (나)환불요구 (다)반복불만인데, _is_risk2 는
#   (나)(다)만 받치고 있었다. (가)는 모델 판정에만 맡겨져 있었다.
# ★ upgrade_risk_level 과 같은 계약: **올리기만 하고 내리지 않는다.**
_ANGRY_WORDS = ("화가 나", "화나", "화났", "화가 났", "열받", "짜증", "분노", "화딱지", "부글부글")
_DISAPPOINTED_WORDS = ("실망", "속상", "아쉽", "아쉬", "서운")

# ★ '아쉽다' 는 ㅂ 불규칙이다. '아쉽' 만 두면 실사용 다수인 "아쉬웠어요" 를 놓친다 —
#   실측에서 '아쉽' 단독은 894건 중 2건만 잡았는데 아쉬움 라벨은 21건이었다.

_TONE_NEGATED = re.compile(r"(않|없|못)")
# "속상한 리뷰에 답글 남겨주셔서" — 리뷰 자체를 가리키는 관용구다(실측 C-X-038, 칭찬).
_SOKSANG_REVIEW = re.compile(r"속상.{0,4}리뷰")
# "이사가게 돼서 아쉽네요"·"없어지면 아쉬울 것 같아요" — 이별·가정법 칭찬이다.
_FAREWELL = ("이사가", "이사를 가", "마지막 주문", "폐업", "떠나요", "떠나게",
             "없어지면", "사라지면", "폐업하면")
# 되묻는 말투 — 감정 단어 없이 짜증을 드러내는 화행.
_RHETORICAL = ("어쩌라는", "어떻게 먹으라", "말이 되나", "이게 맞나", "뭘 어쩌",
               "라는건지", "라는 건지")
# ★ '그냥 버렸'·'손으로 뜯' 같은 '손해 감수 서술' 은 일부러 넣지 않았다.
#   "위생장갑이 없어서 손으로 뜯었네요" 가 별점 5 칭찬이다(실측 C-M-010) —
#   HYGIENE 룰이 같은 문장에서 오탐했던 것과 같은 함정이다.

_TONE_ORDER = {"CALM": 0, "DISAPPOINTED": 1, "ANGRY": 2}
_TONE_NAME = {v: k for k, v in _TONE_ORDER.items()}


def _tone_negated(body: str, end: int, window: int = 8) -> bool:
    """뒤따르는 짧은 구간에 부정어가 있으면 무효다 — "실망한 적이 없어요"."""
    return _TONE_NEGATED.search(body[end:end + window]) is not None


def _angry_hit(body: str) -> bool:
    """분노가 **직접 표현**으로 드러났는가. risk 2 (가) 와 같은 기준이다."""
    return any(
        not _tone_negated(body, m.end())
        for w in _ANGRY_WORDS for m in re.finditer(re.escape(w), body)
    )


def upgrade_tone(text: str, base_tone: str) -> str:
    """모델 tone 을 결정론 룰로 받친다. 올리기만 한다.

    ★ 커버리지가 좁다(실측 재현율 38%). 어휘 없이 상황만으로 감정을 전하는 리뷰는
      못 잡는다 — 그건 프롬프트의 몫이다. 이 룰은 **명시적 표현만** 책임진다.
    ★ 반어법은 일부러 넣지 않았다. 정규식으로 칭찬과 구분되지 않는다."""
    body = text or ""
    level = _TONE_ORDER["ANGRY"] if _angry_hit(body) else 0

    if level < _TONE_ORDER["DISAPPOINTED"]:
        for w in _DISAPPOINTED_WORDS:
            for m in re.finditer(re.escape(w), body):
                if _tone_negated(body, m.end()):
                    continue
                if w == "속상" and _SOKSANG_REVIEW.search(body, m.start()):
                    continue
                if w in ("아쉽", "아쉬", "실망") and any(f in body for f in _FAREWELL):
                    continue
                level = max(level, _TONE_ORDER["DISAPPOINTED"])
        if any(p in body for p in _RHETORICAL) or _REPEAT_COMPLAINT.search(body):
            level = max(level, _TONE_ORDER["DISAPPOINTED"])

    return _TONE_NAME[max(_TONE_ORDER.get(base_tone, 0), level)]


def _is_risk2(body: str) -> bool:
    """(가) 화·분노, (나) 환불·보상 요구, (다) 반복 불만 중 하나가 확인되는가.

    ★ (가)는 2026-09-17 에야 들어왔다. 그전까지 이 함수는 (나)(다)만 받쳤고,
      화·분노는 모델 판정에만 의존했다 — 손님 픽스처 실측에서 미탐 4건이 전부
      이 계열이었다. tone 룰과 같은 어휘를 쓴다(사본을 만들지 않는다)."""
    if _angry_hit(body):
        return True
    if _REFUND_DEMAND.search(body) and not _REFUND_RESOLVED.search(body):
        return True
    return _REPEAT_COMPLAINT.search(body) is not None


def _hits(body: str, reason: str) -> bool:
    """한 위험 사유가 성립하는지 판단한다."""
    if any(kw in body for kw in _RISK_KEYWORDS.get(reason, ())):
        return True
    if any(re.search(p, body) for p in _RISK_PATTERNS.get(reason, ())):
        return True
    if reason == "FOREIGN_OBJECT":
        return (
            _OBJECT_NEAR_DISCOVERY.search(body) is not None
            or _VAGUE_OBJECT_NEAR_DISCOVERY.search(body) is not None
            or _MOUTH_DISCOVERY.search(body) is not None
        )
    if reason == "FOOD_POISONING":
        return any(a in body for a in _ALLERGY) and any(r in body for r in _ALLERGY_REACTION)
    if reason == "HYGIENE":
        # ★ 위생장갑·위생봉투는 물건 이름이지 위생 주장이 아니다(실측 2026-09-17).
        #   "위생장갑이 없어서 손으로 뜯었네요"(별점 5 칭찬)가 risk 3 으로 올라가
        #   T3(opus, T1 의 5배)로 라우팅되고 검수 큐에 쌓였다.
        #   물건 이름을 지운 뒤에도 위생이 남을 때만 주장으로 본다.
        stripped = _HYGIENE_ITEM.sub("", body)
        if "위생" not in stripped:
            return False
        praised = any(p in stripped for p in _HYGIENE_PRAISE)
        negated = any(n in stripped for n in _NEGATION)
        return not (praised and not negated)
    if reason == "REVIEW_TRADE":
        return any(p.search(body) for p in _TRADE_NEAR) and _TRADE_PROMISE.search(body) is not None
    if reason == "UNDERAGE_ALCOHOL":
        return any(m in body for m in _MINOR_WORDS) and _ALCOHOL_SALE.search(body) is not None
    if reason == "PRIVACY_LEAK":
        if _LEAK_NEGATED.search(body):
            return False
        if _LEAK_REPORT.search(body):
            return True
        # 번호든 항목명이든, **제3자의 것**이라는 단서가 함께 있을 때만 유출로 본다.
        # "가게 전화번호 010-…"·"제 전화번호는 010-…" 은 제3자 단서가 없어 통과한다.
        if not _THIRD_PARTY.search(body):
            return False
        # 번호 자체가 적혀 있으면 그 자체로 노출이다. 항목명만 있을 때는 노출 단서를 요구한다.
        if _PHONE_PATTERN.search(body):
            return True
        return _PII_ITEM.search(body) is not None and _PII_EXPOSED.search(body) is not None
    return False


def upgrade_risk_level(text: str, base_level: int) -> tuple[int, list[str]]:
    """문서 12 §1.2: 키워드 히트 시 risk_level 을 3으로 승격한다(하향 금지).
    반환값은 (최종 risk_level, 키워드로 새로 감지된 risk_reasons).

    ★ 이 함수가 절대규칙 3 을 지키는 유일한 결정론적 방어선이다. 모델은 믿을 수 없다 —
      실측에서 haiku 는 "고소할 거야 각오해라" 를 risk 1 로 분류했다.
      tests/test_risk_rule.py 가 트리거 전종과 오탐 케이스를 함께 잠근다.
    ★ 승격만 한다. 어떤 경우에도 base_level 아래로 내리지 않는다.
    """
    body = text or ""
    reasons = [r for r in _RISK_KEYWORDS if _hits(body, r)]
    if reasons:
        level = 3
    elif _is_risk2(body):
        # risk 2 는 위험 '사유'가 아니라 대응 난이도다 — reasons 는 비운다.
        # main.py 가 riskReasons 를 RISK_REASON_VALUES 로 교집합하므로 값을 넣을 수도 없다.
        level = 2
    else:
        level = base_level
    return max(base_level, level), reasons


