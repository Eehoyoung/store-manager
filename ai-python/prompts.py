def format_few_shot(examples) -> str:
    """few-shot 블록을 만든다. 항목은 (리뷰, 답글) 또는 (리뷰, 답글, 슬롯유형) 이다.

    ★ 리뷰가 없는 항목(사장님이 적은 형식·우리 기본값)은 예전에 전부 "답글 형식:" 으로만
      들어갔다. 그러면 모델이 **어떤 리뷰에 쓰는 형식인지** 모른 채 문체만 본다.
      슬롯 유형(THANKS·APOLOGY·GENERAL)이 그 맥락을 이미 알고 있으므로 라벨로 붙인다 —
      추가 비용 0 이고, 감사 형식이 불만 리뷰의 본보기로 읽히는 것을 막는다.
    """
    if not examples:
        return "(참고할 이전 답글 예시 없음 — 업종 표준 톤으로 작성하라)"
    lines = []
    for i, item in enumerate(examples, start=1):
        rt, pt = item[0], item[1]
        slot = item[2] if len(item) > 2 else None
        reply = html.escape(pt, quote=True)
        if rt:
            lines.append(f"{i}. 리뷰: {html.escape(rt, quote=True)}" + chr(10) + f"   답글: {reply}")
        else:
            lines.append(f"{i}. {_SLOT_LABEL.get(slot, '답글 형식')}: {reply}")
    return chr(10).join(lines)


