# "환불 요청했더니 바로 처리해주셔서 감사합니다" — 이 한 건이 좁히기 전 유일한 오탐이었다.
_REFUND_RESOLVED = re.compile(r"(환불|보상|배상)[^.!?]{0,20}(했더니|해\s*주셔|처리해\s*주|받았|해\s*주셨)")

# (다) 반복 불만. 반복 표현 **과** 부정적 사건이 함께 있어야 한다.
#   `이상` 은 "2개 이상"에 걸리므로 `이상하다` 형태로, `짜` 는 짜장·짜파게티를 피해 좁혔다.
_REPEAT_NEG = (
    r"(늦|식어|식었|이상[하해했]|빠지|빠져|누락|줄었|줄어|불어|불었|짜(?![장파])|싱겁|"
    r"엉망|최악|실수|덜\s*익|썩|더럽|딱딱|질기|비린|탔|눅눅|차갑|안\s*왔|안\s*옴|모자라|새서|샜|새어)"
)
_REPEAT_COMPLAINT = re.compile(
    # 저번에도 [문제] … 오늘도  — 같은 문제가 되풀이됐다는 진술
    rf"(저번|지난번|전에도|먼젓번)[^.!?]{{0,20}}{_REPEAT_NEG}[^.!?]{{0,20}}(또|오늘도|이번에도|똑같|마찬가지)"
    # 벌써 N번째 — '벌써·또' 가 없으면 단순한 재주문 언급이라 걸지 않는다
    rf"|(벌써|또)\s*(두|세|네|다섯|몇)\s*번째"
    # 매번/올 때마다 + 부정적 사건
    rf"|(매번|번번이|올\s*때마다|시킬\s*때마다|한두\s*번이\s*아니)[^.!?]{{0,25}}{_REPEAT_NEG}"
)


