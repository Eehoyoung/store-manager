def _seed_mix(persona_seed: int | None, review_id: str, salt: int) -> int:
    """매장 고유성(persona_seed) x 리뷰별 변주(review_id) 를 섞는다.

    ★ 내장 hash() 를 쓰지 말 것. 파이썬은 문자열 해시를 프로세스마다 랜덤화하므로
      (PYTHONHASHSEED) 같은 리뷰가 재생성 때마다 다른 인사말을 받는다. crc32 는 고정이다.

    ★ 곱셈으로 섞지 말 것. `crc32 * k % len(pool)` 은 k 와 len(pool) 이 약수를 공유하면
      값이 몇 개로 접힌다 — 실측(2026-09-17)에서 맺음말 8종 중 **2종이 200건의 82%**를
      먹었다. 소금을 문자열에 넣고 한 번에 해싱하면 풀 길이와 무관하게 고르게 퍼진다."""
    return zlib.crc32(f"{salt}:{persona_seed or 0}:{review_id}".encode("utf-8"))


def _pick(pool: tuple[str, ...], persona_seed: int | None, review_id: str, salt: int) -> str:
    return pool[_seed_mix(persona_seed, review_id, salt) % len(pool)]


def emoji_count_for(category: str, risk_reasons: list[str] | None, use_emoji: bool, emoji_level: int,
                    tone: str | None = None) -> int:
    """이 답글에 넣을 이모지 개수.

    ★ 기본은 2개다(운영자 지시 2026-09-17, V34 로 DB 기본값도 2). 예외는 하나뿐이다 —
      위험 사유가 붙은 불만에는 **0개**. 식중독·이물질 주장에 "확인하겠습니다" 뒤로
      이모지가 붙으면 위로가 아니라 사안을 가볍게 다루는 것으로 읽힌다. 이 초안은 사람
      검수 화면에 그대로 뜨므로(절대규칙 3) 검수자가 보는 첫 화면부터 진지해야 한다."""
    if not use_emoji:
        return 0
    if _style_key(category, risk_reasons, tone) == "COMPLAINT_RISK":
        return 0
    return _EMOJI_COUNT.get(emoji_level, 2)


def style_hint(category: str, risk_reasons: list[str] | None, persona, review_id: str,
               tone: str | None = None, body: str = "") -> str:
    """머리말·맺음말·이모지 지침 블록. 사장님이 직접 적은 opening_style 이 있으면 그것이 이긴다."""
    key = _style_key(category, risk_reasons, tone)
    seed = persona.persona_seed
    own = (getattr(persona, "opening_style", None) or "").strip()
    pool = _opening_pool(key, body)
    opening = html.escape(own, quote=True) if own else _pick(pool, seed, review_id, 31)
    closing = _pick(_CLOSING_POOL[key], seed, review_id, 17)
    n = emoji_count_for(category, risk_reasons, persona.use_emoji, persona.emoji_level, tone)

    lines = [
        "\n[머리말·맺음말]",
        f"- '{opening}' 와 비슷한 말로 시작하라. 토씨까지 같을 필요는 없다.",
        f"- '{closing}' 와 비슷한 말로 끝내라.",
        "- 이 두 문장은 껍데기다. 가운데 본문에서 리뷰에 실제로 답하라.",
    ]
    if n == 0:
        lines.append("- 이모지를 쓰지 마라. 이 리뷰에는 어울리지 않는다.")
    else:
        close_pool = f"{{{', '.join(_EMOJI_CLOSE)}}}"
        if key in ("COMPLAINT", "COMPLAINT_RISK"):
            # 이 풀의 머리말은 전부 사과·유감 문장이라, '머리말 끝' 이 곧 '사과 문장 뒤' 다.
            lines.append(f"- 이모지는 {n}개 쓴다. 전부 맺음말 끝에만 붙인다{close_pool}."
                         " 머리말에는 붙이지 마라.")
        else:
            pools = f"머리말 {{{', '.join(_EMOJI_OPEN)}}} / 맺음말 {close_pool}"
            lines.append(f"- 이모지는 {n}개 쓴다. 머리말 끝과 맺음말 끝에만 붙인다({pools}).")
        lines.append(
            "- ★ 사과·원인·조치 문장 뒤에는 절대 붙이지 마라. 사과 문장 뒤에 웃는 이모지가"
            " 붙으면 위로가 아니라 조롱으로 읽힌다."
        )
    return "\n".join(lines) + "\n"


